function changeLanguage(lang) {
    if (!translations[lang]) return;
    const dict = translations[lang];
    
    console.log(`[i18n] Switched language to: ${lang}`);
    
    const map = {
        '#ui-panel h1': 'title',
        '#toggle-macro span:first-child': 'layer_0',
        '#toggle-micro span:first-child': 'layer_1',
        '#toggle-features span:first-child': 'layer_2',
        '#toggle-supp span:first-child': 'layer_3',
        '#toggle-triadic span:first-child': 'layer_4',
        '.panel-header h2': 'control_title',
        '.indices-panel h3': 'indices_title'
    };
    
    for (const [selector, key] of Object.entries(map)) {
        const el = document.querySelector(selector);
        if (el && dict[key]) {
            el.innerHTML = dict[key];
        }
    }
    
    // Update active button state in language bar
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
}

// Bind click events on startup
document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = e.currentTarget.dataset.lang;
            changeLanguage(lang);
        });
    });
});
