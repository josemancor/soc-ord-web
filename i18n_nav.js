/**
 * Gestor Global de Internacionalización (i18n)
 */
class NexordI18nManager {
    constructor() {
        this.dicts = NEXORD_I18N_DICTS;
        this.currentLang = this.detectInitialLanguage();
    }

    detectInitialLanguage() {
        // 1. Parámetro en URL: ?lang=fr
        try {
            const params = new URLSearchParams(window.location.search);
            const urlLang = params.get('lang');
            if (urlLang && this.dicts[urlLang]) return urlLang;
        } catch (e) {}

        // 2. Almacenamiento local (localStorage)
        try {
            const saved = localStorage.getItem('nexord_lang');
            if (saved && this.dicts[saved]) return saved;
        } catch (e) {}

        // 3. Idioma del navegador
        try {
            const navLang = (navigator.language || navigator.userLanguage || '').slice(0, 2).toLowerCase();
            if (this.dicts[navLang]) return navLang;
        } catch (e) {}

        // 4. Por defecto: Español
        return 'es';
    }

    setLanguage(lang) {
        if (!this.dicts[lang]) return;
        this.currentLang = lang;
        try {
            localStorage.setItem('nexord_lang', lang);
        } catch (e) {}
        document.documentElement.lang = lang;

        this.applyTranslations();
        this.updateSelectorUI();

        // Disparar evento personalizado para otros scripts (p.ej. VISORD 3D Engine)
        window.dispatchEvent(new CustomEvent('nexord:languageChange', { detail: { lang } }));
        if (typeof changeLanguage === 'function') {
            try { changeLanguage(lang); } catch (e) {}
        }
    }

    applyTranslations() {
        const dict = this.dicts[this.currentLang];
        if (!dict) return;

        // Traducir todos los elementos marcados con data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = dict[key];
                } else {
                    el.innerHTML = dict[key];
                }
            }
        });

        // Traducir atributos específicos (p.ej. title, alt, placeholder)
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (dict[key]) el.title = dict[key];
        });
    }

    updateSelectorUI() {
        const dict = this.dicts[this.currentLang];
        if (!dict) return;

        // Actualizar botón del selector
        const flagEl = document.getElementById('lang-current-flag');
        const codeEl = document.getElementById('lang-current-code');
        if (flagEl) flagEl.textContent = dict._lang_flag;
        if (codeEl) codeEl.textContent = dict._lang_short;

        // Marcar opción activa en el dropdown
        document.querySelectorAll('.lang-opt').forEach(opt => {
            const isActive = opt.getAttribute('data-lang') === this.currentLang;
            opt.classList.toggle('active', isActive);
        });
    }

    init() {
        this.setLanguage(this.currentLang);
        this.bindEvents();
    }

    bindEvents() {
        const picker = document.getElementById('nexord-lang-picker');
        const pickerBtn = document.getElementById('lang-picker-btn');

        if (pickerBtn && picker) {
            pickerBtn.addEventListener('click', (e) => {
                e.stopPropagation();
                picker.classList.toggle('open');
            });

            // Cerrar al hacer clic fuera
            document.addEventListener('click', (e) => {
                if (!picker.contains(e.target)) {
                    picker.classList.remove('open');
                }
            });
        }

        // Delegación de clic en opciones de idioma
        document.querySelectorAll('.lang-opt').forEach(opt => {
            opt.addEventListener('click', (e) => {
                e.stopPropagation();
                const lang = opt.getAttribute('data-lang');
                this.setLanguage(lang);
                if (picker) picker.classList.remove('open');
            });
        });
    }
}

// Instancia global
window.nexordI18n = new NexordI18nManager();

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        window.nexordI18n.init();
    });
} else {
    window.nexordI18n.init();
}
